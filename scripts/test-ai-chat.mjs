import { chromium } from 'playwright';
const b=await chromium.launch({headless:true});
const p=await b.newPage({viewport:{width:1280,height:900}});
const errs=[]; p.on('pageerror',e=>errs.push(e.message));
await p.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
await p.waitForTimeout(1500);
console.log('status(before open)=',await p.locator('#aiChatStatus').textContent());
await p.locator('#aiChatToggle').click();
await p.waitForTimeout(800);
console.log('open=',await p.locator('#aiChat').evaluate(e=>e.classList.contains('is-open')));
console.log('status=',await p.locator('#aiChatStatus').textContent());
console.log('welcome=',(await p.locator('#aiChatMessages').innerText()).slice(0,120));
await p.locator('#aiChatInput').fill('图仓怎么安装？');
await p.locator('.ai-chat-send').click();
await p.waitForTimeout(4000);
console.log('messages=',(await p.locator('#aiChatMessages').innerText()).slice(0,400));
console.log('errors=',errs);
await b.close();
