import { createHash } from "node:crypto";
import { copyFile, mkdir, readFile, readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import JSZip from "jszip";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const extDir = path.join(root, "extension");
const siteDownloads = path.join(root, "site", "downloads");
const manifest = JSON.parse(await readFile(path.join(extDir, "manifest.json"), "utf8"));
const version = manifest.version;
const zipName = `picharvest-extension-v${version}.zip`;

await mkdir(siteDownloads, { recursive: true });
await mkdir(path.join(extDir, "lib"), { recursive: true });

// Content scripts are classic scripts; bundle the tested extractor and the runtime together.
const extractor = await readFile(path.join(extDir, "src", "extractor.js"), "utf8");
const runtime = await readFile(path.join(extDir, "src", "content.js"), "utf8");
await writeFile(
  path.join(extDir, "content.js"),
  `/* PicHarvest bundled content script · generated by scripts/build.mjs */\n${extractor}\n\n${runtime}\n`,
  "utf8"
);

await copyFile(
  path.join(root, "node_modules", "jszip", "dist", "jszip.min.js"),
  path.join(extDir, "lib", "jszip.min.js")
);
await copyFile(
  path.join(extDir, "icons", "icon128.png"),
  path.join(root, "site", "assets", "icon128.png")
);

const excluded = new Set(["src", path.join("icons", "icon1024.png")]);
async function walk(dir, base = "") {
  const files = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const relative = base ? path.join(base, entry.name) : entry.name;
    if (excluded.has(relative)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...await walk(full, relative));
    else files.push({ full, relative });
  }
  return files;
}

const files = await walk(extDir);
const manifestFiles = files.filter((file) => file.relative === "manifest.json");
if (!manifestFiles.length) throw new Error("manifest.json missing from build");

const zip = new JSZip();
let rawBytes = 0;
for (const file of files.sort((a, b) => a.relative.localeCompare(b.relative))) {
  const data = await readFile(file.full);
  rawBytes += data.byteLength;
  zip.file(file.relative.split(path.sep).join("/"), data);
}
const archive = await zip.generateAsync({
  type: "nodebuffer",
  compression: "DEFLATE",
  compressionOptions: { level: 9 },
  platform: "DOS"
});
const outPath = path.join(siteDownloads, zipName);
await writeFile(outPath, archive);
const digest = createHash("sha256").update(archive).digest("hex");
await writeFile(path.join(siteDownloads, "SHA256.txt"), `${digest}  ${zipName}\n`, "utf8");
await writeFile(
  path.join(siteDownloads, "version.json"),
  JSON.stringify({
    name: manifest.name,
    version,
    file: zipName,
    bytes: archive.byteLength,
    sha256: digest,
    builtAt: new Date().toISOString()
  }, null, 2) + "\n",
  "utf8"
);

const size = (await stat(outPath)).size;
console.log(`Built extension/content.js from ${extractor.length + runtime.length} chars`);
console.log(`Built ${zipName}: ${files.length} files, ${(rawBytes / 1024).toFixed(1)} KiB raw, ${(size / 1024).toFixed(1)} KiB zipped`);
console.log(`SHA256 ${digest}`);
